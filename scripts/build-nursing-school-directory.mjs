import { mkdir, writeFile } from 'node:fs/promises'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const __dirname = dirname(fileURLToPath(import.meta.url))
const projectRoot = resolve(__dirname, '..')
const outputPath = resolve(projectRoot, 'src/data/generated-nursing-schools.ts')

const apiKey = process.env.COLLEGE_SCORECARD_API_KEY || process.env.API_DATA_GOV_KEY || 'DEMO_KEY'
const perPage = Number(process.env.COLLEGE_SCORECARD_PER_PAGE || 100)
const cipCodes = (process.env.NURSING_CIP_CODES || '5138,5139')
  .split(',')
  .map((code) => code.trim())
  .filter(Boolean)

const cipDescriptions = {
  '5138': 'Registered Nursing, Nursing Administration, Nursing Research and Clinical Nursing',
  '5139': 'Practical Nursing, Vocational Nursing and Nursing Assistants',
}

const fields = [
  'id',
  'school.name',
  'school.city',
  'school.state',
  'school.school_url',
  'latest.programs.cip_4_digit',
].join(',')

const slug = (value) =>
  String(value)
    .toLowerCase()
    .replace(/&/g, 'and')
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '')

const escapeString = (value) => JSON.stringify(value ?? '')

async function fetchJson(url) {
  const response = await fetch(url)
  const text = await response.text()
  let json
  try {
    json = JSON.parse(text)
  } catch {
    throw new Error(`College Scorecard returned non-JSON response: ${text.slice(0, 200)}`)
  }
  if (!response.ok || json.error) {
    const message = json.error?.message || response.statusText
    throw new Error(`College Scorecard request failed: ${message}`)
  }
  return json
}

function extractMatchingPrograms(result, cipCode) {
  const programs = result['latest.programs.cip_4_digit']
  if (!Array.isArray(programs)) return []
  return programs.filter((program) => String(program.code) === cipCode)
}

async function fetchSchoolsForCip(cipCode) {
  const collected = []
  let page = 0
  let total = Infinity

  while (page * perPage < total) {
    const params = new URLSearchParams({
      api_key: apiKey,
      fields,
      per_page: String(perPage),
      page: String(page),
      'latest.programs.cip_4_digit.code': cipCode,
    })
    const url = `https://api.data.gov/ed/collegescorecard/v1/schools?${params.toString()}`
    const json = await fetchJson(url)
    total = json.metadata?.total ?? 0

    for (const result of json.results ?? []) {
      const matchingPrograms = extractMatchingPrograms(result, cipCode)
      if (!matchingPrograms.length) continue

      collected.push({
        scorecardId: Number(result.id),
        name: result['school.name'],
        city: result['school.city'],
        state: result['school.state'],
        website: result['school.school_url'],
        programCodes: [cipCode],
        programTitles: [
          ...new Set(
            matchingPrograms
              .map((program) => program.title || cipDescriptions[cipCode])
              .filter(Boolean),
          ),
        ],
      })
    }

    page += 1
  }

  return collected
}

function mergeSchools(schools) {
  const merged = new Map()
  for (const school of schools) {
    if (!school.name || !school.city || !school.state) continue
    const key = `${school.name}|${school.city}|${school.state}`.toLowerCase()
    const existing = merged.get(key)
    if (!existing) {
      merged.set(key, school)
      continue
    }
    merged.set(key, {
      ...existing,
      programCodes: [...new Set([...(existing.programCodes ?? []), ...(school.programCodes ?? [])])],
      programTitles: [...new Set([...(existing.programTitles ?? []), ...(school.programTitles ?? [])])],
      website: existing.website ?? school.website,
    })
  }
  return [...merged.values()].sort((a, b) => a.name.localeCompare(b.name))
}

function renderTypeScript(schools) {
  const rows = schools
    .map((school) => {
      const id = `scorecard-${school.scorecardId || slug(`${school.name}-${school.city}-${school.state}`)}`
      const website = school.website ? `,\n    website: ${escapeString(school.website)}` : ''
      return `  {
    id: ${escapeString(id)},
    scorecardId: ${Number(school.scorecardId) || 'undefined'},
    name: ${escapeString(school.name)},
    city: ${escapeString(school.city)},
    state: ${escapeString(school.state)},
    sourceHint: 'College Scorecard Nursing CIP',
    programCodes: ${JSON.stringify(school.programCodes ?? [])},
    programTitles: ${JSON.stringify(school.programTitles ?? [])}${website},
  }`
    })
    .join(',\n')

  return `import type { NursingSchoolOption } from './nursing-schools'

// Generated by \`npm run build:nursing-directory\`.
// Source: U.S. Department of Education College Scorecard schools API.
// Included CIP-4 codes: ${cipCodes.join(', ')}.
export const generatedNursingSchoolOptions = [
${rows}
] satisfies NursingSchoolOption[]
`
}

async function main() {
  if (apiKey === 'DEMO_KEY') {
    console.warn('Using api.data.gov DEMO_KEY. For a full import, set COLLEGE_SCORECARD_API_KEY to avoid rate limits.')
  }

  const schoolsByCode = []
  for (const cipCode of cipCodes) {
    console.log(`Fetching College Scorecard nursing schools for CIP ${cipCode}...`)
    schoolsByCode.push(...(await fetchSchoolsForCip(cipCode)))
  }

  const schools = mergeSchools(schoolsByCode)
  await mkdir(dirname(outputPath), { recursive: true })
  await writeFile(outputPath, renderTypeScript(schools), 'utf8')
  console.log(`Wrote ${schools.length} nursing program schools to ${outputPath}`)
}

main().catch((error) => {
  console.error(error.message)
  process.exit(1)
})
